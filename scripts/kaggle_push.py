"""Bundle lanedet + kaggle/tusimple_eval.py into one Kaggle script and push it as a private notebook.

The notebook runs on Kaggle with the TuSimple dataset attached, so nothing is downloaded locally.
Needs the Kaggle CLI (`pip install kaggle`) and an API token in ~/.kaggle/kaggle.json.

    python scripts/kaggle_push.py                      # build and push
    kaggle kernels status <user>/lanedet-tusimple-eval  # poll
    kaggle kernels output <user>/lanedet-tusimple-eval -p results/kaggle
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import os
import subprocess
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SLUG = "lanedet-tusimple-eval"
TITLE = "lanedet TuSimple eval"

BOOTSTRAP = '''"""lanedet on TuSimple: generated by scripts/kaggle_push.py from the lanedet repo. Do not edit."""
import base64, io, runpy, sys, tarfile

PAYLOAD = "{payload}"
DEST = "/tmp/lanedet_src"
with tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz") as tf:
    tf.extractall(DEST)
sys.path.insert(0, DEST)
runpy.run_path(DEST + "/tusimple_eval.py", run_name="__main__")
'''


def kaggle_user() -> str:
    if os.environ.get("KAGGLE_USERNAME"):
        return os.environ["KAGGLE_USERNAME"]
    token = Path.home() / ".kaggle" / "kaggle.json"
    return json.loads(token.read_text())["username"]


def payload() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tf:
        for path in sorted((ROOT / "src" / "lanedet").glob("*.py")):
            tf.add(path, arcname=f"lanedet/{path.name}")
        tf.add(ROOT / "kaggle" / "tusimple_eval.py", arcname="tusimple_eval.py")
    return base64.b64encode(buf.getvalue()).decode("ascii")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--user", help="Kaggle username (default: from the API token)")
    ap.add_argument("--dataset", default="manideep1108/tusimple", help="Kaggle dataset to attach")
    ap.add_argument("--build-dir", default="build/kaggle")
    ap.add_argument("--no-push", action="store_true", help="only write the notebook folder")
    args = ap.parse_args()

    user = args.user or kaggle_user()
    out = Path(args.build_dir)
    out.mkdir(parents=True, exist_ok=True)
    code_file = f"{SLUG}.py"
    (out / code_file).write_text(BOOTSTRAP.format(payload=payload()), encoding="utf-8")
    meta = {
        "id": f"{user}/{SLUG}",
        "title": TITLE,
        "code_file": code_file,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,
        "enable_tpu": False,
        "enable_internet": False,
        "dataset_sources": [args.dataset],
        "competition_sources": [],
        "kernel_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"wrote {out / code_file} ({(out / code_file).stat().st_size / 1024:.0f} KB)")
    if not args.no_push:
        subprocess.run(["kaggle", "kernels", "push", "-p", str(out)], check=True)


if __name__ == "__main__":
    main()
